import socket
import threading
import json
import time
from datetime import datetime

# CONFIGURAÇÕES
HOST = "127.0.0.1"
NUM_CLIENTES = 3
TIMEOUT = 2.0

servidor_pronto = threading.Event()
dados_servidor = {}
lock_log = threading.Lock()


# REGISTRO DAS MENSAGENS
def log(origem, mensagem):
    with lock_log:
        horario = datetime.now().strftime("%H:%M:%S")
        print(f"{horario} [{origem}] {mensagem}", flush=True)


# ENVIO DE MENSAGENS JSON PELO TCP
def enviar_mensagem(conexao, mensagem):
    dados = json.dumps(mensagem) + "\n"
    conexao.sendall(dados.encode("utf-8"))


# RECEBIMENTO DE MENSAGENS JSON
def receber_mensagem(conexao, buffer=""):
    while "\n" not in buffer:
        parte = conexao.recv(4096)
        if not parte:
            raise ConnectionError("Conexão encerrada pelo outro componente.")
        buffer += parte.decode("utf-8")

    linha, restante = buffer.split("\n", 1)
    return json.loads(linha), restante


# SERVIDOR COORDENADOR
def executar_servidor():
    conexoes = {}
    buffers = {}
    resultados = {}
    clientes_ativos = set()

    servidor = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    servidor.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    servidor.bind((HOST, 0))
    servidor.listen(NUM_CLIENTES)

    porta = servidor.getsockname()[1]
    dados_servidor["porta"] = porta

    log("SERVIDOR", f"Iniciado em {HOST}:{porta}")
    log("SERVIDOR", "Aguardando os três clientes...")
    servidor_pronto.set()

    try:
        # 1. REGISTRO DOS CLIENTES
        while len(conexoes) < NUM_CLIENTES:
            conexao, endereco = servidor.accept()
            conexao.settimeout(TIMEOUT)

            mensagem, restante = receber_mensagem(conexao)
            cliente_id = mensagem["cliente_id"]

            conexoes[cliente_id] = conexao
            buffers[cliente_id] = restante
            clientes_ativos.add(cliente_id)

            log("SERVIDOR", f"{cliente_id} conectado: {endereco}")

            enviar_mensagem(conexao, {
                "tipo": "REGISTRO_CONFIRMADO",
                "mensagem": "Registro realizado com sucesso."
            })

        # 2. DISTRIBUIÇÃO DAS TAREFAS
        tarefas = {
            "CLIENTE 1": [1, 2, 3],
            "CLIENTE 2": [4, 5, 6],
            "CLIENTE 3": [7, 8, 9]
        }

        for cliente_id, conexao in conexoes.items():
            enviar_mensagem(conexao, {
                "tipo": "TAREFA",
                "numeros": tarefas[cliente_id]
            })
            log("SERVIDOR", f"Tarefa enviada para {cliente_id}: {tarefas[cliente_id]}")

        # 3. RECEBIMENTO DOS RESULTADOS
        for cliente_id, conexao in conexoes.items():
            try:
                resposta, buffers[cliente_id] = receber_mensagem(
                    conexao, buffers[cliente_id]
                )

                if resposta["tipo"] == "RESULTADO":
                    resultados[cliente_id] = resposta["resultado"]
                    log("SERVIDOR", f"Resultado de {cliente_id}: {resposta['resultado']}")

            except socket.timeout:
                log("SERVIDOR", f"Tempo esgotado ao aguardar {cliente_id}.")
                clientes_ativos.discard(cliente_id)

        # 4. CONSOLIDAÇÃO E SINCRONIZAÇÃO
        estado_global = {
            "resultados_individuais": resultados,
            "resultado_global": sum(resultados.values())
        }

        log("SERVIDOR", f"Resultado global: {estado_global['resultado_global']}")

        for cliente_id in list(clientes_ativos):
            enviar_mensagem(conexoes[cliente_id], {
                "tipo": "SINCRONIZACAO",
                "estado_global": estado_global
            })

        # CONFIRMAÇÃO ACK
        for cliente_id in list(clientes_ativos):
            try:
                resposta, buffers[cliente_id] = receber_mensagem(
                    conexoes[cliente_id], buffers[cliente_id]
                )

                if resposta["tipo"] == "ACK_SINCRONIZACAO":
                    log("SERVIDOR", f"ACK recebido de {cliente_id}.")

            except socket.timeout:
                log("SERVIDOR", f"{cliente_id} não confirmou a sincronização.")
                clientes_ativos.discard(cliente_id)

        # 5. TESTE DE DISPONIBILIDADE: PING/PONG
        for cliente_id in list(clientes_ativos):
            enviar_mensagem(conexoes[cliente_id], {"tipo": "PING"})
            log("SERVIDOR", f"PING enviado para {cliente_id}.")

        for cliente_id in list(clientes_ativos):
            try:
                resposta, buffers[cliente_id] = receber_mensagem(
                    conexoes[cliente_id], buffers[cliente_id]
                )

                if resposta["tipo"] == "PONG":
                    log("SERVIDOR", f"PONG recebido de {cliente_id}. Nó ativo.")

            except socket.timeout:
                log("SERVIDOR", f"FALHA: {cliente_id} não respondeu em {TIMEOUT} segundos.")
                clientes_ativos.discard(cliente_id)

            except (ConnectionError, OSError):
                log("SERVIDOR", f"Conexão perdida com {cliente_id}.")
                clientes_ativos.discard(cliente_id)

        log("SERVIDOR", f"Clientes ativos ao final: {sorted(clientes_ativos)}")

        # ENCERRAMENTO
        for cliente_id, conexao in conexoes.items():
            try:
                enviar_mensagem(conexao, {"tipo": "ENCERRAR"})
            except OSError:
                pass

    except Exception as erro:
        log("SERVIDOR", f"Erro durante a execução: {erro}")

    finally:
        for conexao in conexoes.values():
            try:
                conexao.close()
            except OSError:
                pass

        servidor.close()
        log("SERVIDOR", "Servidor encerrado.")


# CLIENTES DISTRIBUÍDOS
def executar_cliente(numero_cliente, simular_falha=False):
    cliente_id = f"CLIENTE {numero_cliente}"
    buffer = ""
    cliente = socket.socket(socket.AF_INET, socket.SOCK_STREAM)

    servidor_pronto.wait()
    porta = dados_servidor["porta"]
    cliente.settimeout(TIMEOUT + 3)

    try:
        log(cliente_id, f"Conectando ao servidor na porta {porta}...")
        cliente.connect((HOST, porta))

        enviar_mensagem(cliente, {
            "tipo": "REGISTRO",
            "cliente_id": cliente_id
        })

        resposta, buffer = receber_mensagem(cliente, buffer)
        log(cliente_id, resposta["mensagem"])

        # RECEBIMENTO E EXECUÇÃO DA TAREFA
        mensagem, buffer = receber_mensagem(cliente, buffer)

        if mensagem["tipo"] == "TAREFA":
            numeros = mensagem["numeros"]
            log(cliente_id, f"Tarefa recebida: {numeros}")

            time.sleep(0.5 + numero_cliente * 0.2)
            resultado = sum(numeros)

            enviar_mensagem(cliente, {
                "tipo": "RESULTADO",
                "cliente_id": cliente_id,
                "resultado": resultado
            })

            log(cliente_id, f"Resultado calculado e enviado: {resultado}")

        # RECEBIMENTO DA SINCRONIZAÇÃO
        mensagem, buffer = receber_mensagem(cliente, buffer)

        if mensagem["tipo"] == "SINCRONIZACAO":
            log(cliente_id, f"Estado global recebido: {mensagem['estado_global']}")

            enviar_mensagem(cliente, {
                "tipo": "ACK_SINCRONIZACAO",
                "cliente_id": cliente_id
            })

            log(cliente_id, "Confirmação ACK enviada.")

        # VERIFICAÇÃO DE DISPONIBILIDADE
        mensagem, buffer = receber_mensagem(cliente, buffer)

        if mensagem["tipo"] == "PING":
            log(cliente_id, "Solicitação PING recebida.")

            if simular_falha:
                log(cliente_id, "Falha simulada: resposta PONG não será enviada.")
                time.sleep(TIMEOUT + 1)
                return

            enviar_mensagem(cliente, {
                "tipo": "PONG",
                "cliente_id": cliente_id
            })

            log(cliente_id, "Resposta PONG enviada.")

            mensagem, buffer = receber_mensagem(cliente, buffer)

            if mensagem["tipo"] == "ENCERRAR":
                log(cliente_id, "Solicitação de encerramento recebida.")

    except socket.timeout:
        log(cliente_id, "Tempo limite de comunicação excedido.")

    except (ConnectionError, OSError) as erro:
        log(cliente_id, f"Conexão encerrada: {erro}")

    finally:
        cliente.close()
        log(cliente_id, "Cliente finalizado.")


# INICIALIZAÇÃO DO SISTEMA
log("SISTEMA", "Iniciando simulação do sistema distribuído.")

thread_servidor = threading.Thread(target=executar_servidor)
thread_servidor.start()

servidor_pronto.wait()

threads_clientes = []

for numero in range(1, NUM_CLIENTES + 1):
    thread_cliente = threading.Thread(
        target=executar_cliente,
        args=(numero, numero == 3)
    )
    threads_clientes.append(thread_cliente)
    thread_cliente.start()

for thread_cliente in threads_clientes:
    thread_cliente.join()

thread_servidor.join()

log("SISTEMA", "Simulação finalizada.")